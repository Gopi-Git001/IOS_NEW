// Writes sites/sugardepth/src/styles/tokens.css from brand/tokens.json, the one source of the brand colors.
// The app imports brand/tokens.json directly (src/theme.ts). `--check` fails if the CSS is out of date (CI).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url).pathname;
const t = JSON.parse(readFileSync(`${root}brand/tokens.json`, 'utf8'));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const lines = [
  ...Object.entries(t.colors).map(([k, v]) => `  --sd-${kebab(k)}: ${v};`),
  ...t.ambient.base.map((v, i) => `  --sd-ambient-${i}: ${v};`),
  ...['glowTeal', 'glowIndigo', 'glowAmber'].map((k) => `  --sd-${kebab(k)}: ${t.ambient[k]};`),
  `  --sd-font-sans: '${t.fonts.sans}';`,
  `  --sd-font-serif: '${t.fonts.serif}';`,
  ...Object.entries(t.radius).map(([k, v]) => `  --sd-radius-${k}: ${v}px;`),
];
const css = `/* Generated by scripts/sync-tokens.mjs from brand/tokens.json. Do not edit; run \`npm run tokens\`. */\n:root {\n${lines.join('\n')}\n}\n`;
const out = `${root}sites/sugardepth/src/styles/tokens.css`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== css) {
    console.error('sites/sugardepth/src/styles/tokens.css is out of date with brand/tokens.json. Run `npm run tokens`.');
    process.exit(1);
  }
  console.log('Brand tokens in sync.');
} else {
  writeFileSync(out, css);
  console.log(`Wrote ${out}`);
}
